#!/usr/bin/env python3
# Generates src/Unicode.cpp, src/Languages.cpp and src/LineBreak.cpp from lib/ImGuiColorTextEdit.
# Run after updating the submodule.
import re, subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = (root / 'lib/ImGuiColorTextEdit/TextEditor.cpp').read_text()
commit = subprocess.run(['git', '-C', str(root / 'lib/ImGuiColorTextEdit'), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()

def section(start_pattern, end_pattern=None):
    start = re.search(start_pattern, source, re.M).start()
    end = re.search(end_pattern, source[start:], re.M).start() + start if end_pattern else len(source)
    return source[start:end]

def drop_function(text, signature_pattern):
    m = re.search(signature_pattern, text, re.M)
    if not m: return text
    depth, j = 0, text.index('{', m.start())
    while True:
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    return text[:m.start()] + text[j + 1:]

def drop_banners(text):
    return re.sub(r'^//\n//\t[^\n]*\n//\n', '', text, flags=re.M)

# Replaces `old` and the lowercase letter after it with `new` and that letter in uppercase.
def capitalize_after(text, old, new):
    return re.sub(re.escape(old) + '([a-z])', lambda m: new + m.group(1).upper(), text)

def common(text):
    text = drop_banners(text)
    text = text.replace('ImWchar16', 'char16_t').replace('ImWchar32', 'char32_t').replace('ImWchar', 'uint64_t')
    text = text.replace('TextEditor::CodePoint::getGlyphWidth', 'GlyphWidth')
    text = capitalize_after(text, 'TextEditor::CodePoint::', '')
    return text.replace('\t', '    ')

def generated(description, includes, body):
    return (f'// Generated by script/PortUpstream.py from ImGuiColorTextEdit {commit}. Do not edit.\n// {description}\n\n'
            f'{includes}\n\nnamespace ipte {{\n{body.strip()}\n}} // namespace ipte\n')

def unicode_cpp():
    text = section(r'^//\n//\tRange table types', r'//\n//\tTextEditor::updatePalette\n')
    for name in ['skipBOM', 'read', 'write']:
        text = drop_function(text, r'^[^\n]*TextEditor::CodePoint::' + name + r'\(')
    text = drop_function(text, r'^static inline ImWchar uch\(')
    text = drop_function(text, r'^static inline char sch\(')
    return generated('Unicode tables and predicates.', '#include "Unicode.h"\n\n#include <cstddef>\n#include <iterator>', common(text))

def languages_cpp():
    text = common(section(r'^//\n//\tgetCStyleIdentifier'))
    text = text.replace('TextEditor::Iterator', 'Iterator')
    text = capitalize_after(text, 'TextEditor::Color::', 'Color::').replace('TextEditor::Color', 'Color')
    text = re.sub(r'const TextEditor::Language\* TextEditor::Language::(\w+)\(\)', r'const Language *\1()', text)
    text = text.replace('static TextEditor::Language language;', 'static Language language;')
    text = capitalize_after(text, 'language.', 'language.')
    return generated('Language definitions and tokenizers.', '#include "Language.h"\n\n#include "Unicode.h"', text)

def linebreak_cpp():
    text = common(section(r'^//\n//\tline break class types for codepoints', r'^//\n//\tTextEditor::LineBreak::classify'))
    text = capitalize_after(text, 'TextEditor::BreakOption::', 'BreakOption::')
    text = text.replace('TextEditor::BreakOption', 'BreakOption').replace('TextEditor::LineBreakConfig', 'LineBreakConfig')
    text = text.replace('TextEditor::Glyph* glyphs;', 'const uint64_t *glyphs;').replace('glyphs[pos].codepoint', 'glyphs[pos]')
    wrapper = '''
void ClassifyAnnex14(const LineBreakConfig &config, const uint64_t *glyphs, size_t size, BreakOption *out) {
    LineBreakState state;
    state.glyphs = glyphs;
    state.size = size;
    for (size_t i = 0; i < size; i++) {
        state.push(LineBreakGlyph(glyphs[i], getLineBreakClass(glyphs[i]), i));
        const auto breakOption = applyRules(config, state);
        if (i) out[i - 1] = breakOption;
    }
}
'''
    return generated('Unicode Annex 14 line breaking classes and rules.', '#include "LineBreak.h"\n\n#include "Unicode.h"\n\n#include <iterator>\n#include <limits>\n#include <unordered_set>', text.strip() + '\n' + wrapper)

(root / 'src/LineBreak.cpp').write_text(linebreak_cpp())
(root / 'src/Unicode.cpp').write_text(unicode_cpp())
(root / 'src/Languages.cpp').write_text(languages_cpp())
subprocess.run(['/opt/homebrew/opt/llvm/bin/clang-format', '-i', str(root / 'src/Unicode.cpp'), str(root / 'src/Languages.cpp'), str(root / 'src/LineBreak.cpp')], check=True)
print('wrote src/Unicode.cpp, src/Languages.cpp and src/LineBreak.cpp from', commit)
